#requires -Version 7.2
# Fake Editor EXEs verify native launch/ownership boundaries only, never UE/assets.
[CmdletBinding()]
param()
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
if (-not $IsWindows) { throw 'Windows launcher fixture required.' }
$PSNativeCommandUseErrorActionPreference=$false
$temporary=Join-Path ([IO.Path]::GetTempPath()) ('WJ movement review '+[guid]::NewGuid().ToString('N'))
$tools=Split-Path -Parent $PSScriptRoot
$launcher=Join-Path $tools 'PrepareMovementReview.ps1'
$windowsPowerShell=(Get-Command powershell.exe -CommandType Application).Source
$revision='2222222222222222222222222222222222222222'
$previousPhase=$env:WJ_REVIEW_FIXTURE_FAIL_PHASE; $previousCapture=$env:WJ_REVIEW_FIXTURE_CAPTURE
$previousMode=$env:WJ_REVIEW_FIXTURE_MODE
$game=$null; $checks=0
function Assert([bool]$Condition,[string]$Message) {
    if (-not $Condition) { throw $Message }; $script:checks++
}
function Invoke-Review([switch]$PrepareOnly,[switch]$RunOnly) {
    $values=@('-NoLogo','-NoProfile','-ExecutionPolicy','Bypass','-File',$launcher,'-Revision',$revision,'-SampleRoot',$sample,'-EngineRoot',$engine,'-OutputRoot',$output,'-LocalToolsRoot',$cacheRoot,'-TimeoutSeconds','30')
    if ($PrepareOnly) { $values+='-PrepareOnly' }; if ($RunOnly) { $values+='-RunOnly' }
    $script:lastOutput=@(& $windowsPowerShell @values 2>&1); $script:code=$LASTEXITCODE
    $script:lastOutput | ForEach-Object { Write-Host $_ }
}
try {
    $sample=Join-Path $temporary ('Sample '+[char]0xAC08+[char]0xB9B4+[char]0xB9AC)
    $engine=Join-Path $temporary 'Fixture Engine'; $output=Join-Path $temporary 'Private Reports'; $cacheRoot=Join-Path $temporary 'Local Tools'
    foreach ($path in @((Join-Path $sample 'Config'),(Join-Path $engine 'Engine/Build'),(Join-Path $engine 'Engine/Binaries/Win64'))) { [void][IO.Directory]::CreateDirectory($path) }
    $project=Join-Path $sample 'FixtureSample.uproject'
    $original='{"FileVersion":3,"EngineAssociation":"5.8","Plugins":[{"Name":"PythonScriptPlugin","Enabled":false}]}'
    [IO.File]::WriteAllText($project,$original)
    $config=Join-Path $sample 'Config/DefaultEngine.ini'
    [IO.File]::WriteAllText($config,"[/Script/EngineSettings.GameMapsSettings]`nGameDefaultMap=/Game/Fixture/Map.Map`n")
    $configHash=(Get-FileHash -LiteralPath $config).Hash
    [IO.File]::WriteAllText((Join-Path $engine 'Engine/Build/Build.version'),'{"MajorVersion":5,"MinorVersion":8,"PatchVersion":0,"BranchName":"fixture"}')
    $source=Join-Path $temporary 'FixtureEditor.cs'
    [IO.File]::WriteAllText($source,@'
using System;
using System.IO;
using System.Threading;
public class FixtureEditor {
    public static int Main(string[] args) {
        var capture=Environment.GetEnvironmentVariable("WJ_REVIEW_FIXTURE_CAPTURE");
        var phase=Environment.GetEnvironmentVariable("WORD_JOURNEY_REVIEW_PHASE");
        if(Array.IndexOf(args,"-run=pythonscript")<0) {
            File.WriteAllLines(capture+".game",args);
            if(Array.IndexOf(args,"-NullRHI")>=0) return 41;
            Thread.Sleep(20000); return 0;
        }
        File.AppendAllText(capture,phase+":"+System.Diagnostics.Process.GetCurrentProcess().Id+"\n");
        if(args.Length!=10 || !File.Exists(args[0]) || !Path.GetFileName(args[0]).StartsWith("WJInspect_")) return 42;
        if(args[1]!="-run=pythonscript" || args[2].IndexOf("movement_review.py")<0 || args[5]!="-NullRHI") return 43;
        var report=Environment.GetEnvironmentVariable("WORD_JOURNEY_REVIEW_REPORT");
        if(phase==Environment.GetEnvironmentVariable("WJ_REVIEW_FIXTURE_FAIL_PHASE")) {
            File.WriteAllText(report,"{\"schemaVersion\":1,\"status\":\"FAILED\",\"error\":\"Intentional fixture failure\"}"); return 0;
        }
        var sourceEditor=Environment.GetEnvironmentVariable("WJ_REVIEW_FIXTURE_MODE")=="sampleEditor";
        var status=sourceEditor ? (phase=="verify" ? "SAMPLE_EDITOR_REVIEW_RELOADED" : "SAMPLE_EDITOR_REVIEW_READY") : (phase=="verify" ? "MOTION_REVIEW_ASSETS_RELOADED" : "MOTION_REVIEW_ASSETS_SAVED");
        var launch=sourceEditor ? "{\"mode\":\"sampleEditor\",\"manualCharacterSelectionRequired\":true,\"map\":\"/Game/Fixture/Map\",\"gameModeClass\":\"\",\"sourcePawn\":\"\"}" : "{\"mode\":\"boundKellan\",\"manualCharacterSelectionRequired\":false,\"map\":\"/Game/Fixture/Map\",\"gameModeClass\":\"/Game/WordJourneyDev/MovementReview/r_0000000000000000/BP_MovementReview.BP_MovementReview_C\",\"sourcePawn\":\"/Game/Fixture/Person.Person\"}";
        // No .uasset/.umap files are generated by this fixture.
        File.WriteAllText(report,"{\"fixtureOnly\":true,\"schemaVersion\":1,\"status\":\""+status+"\",\"graphicsVerified\":false,\"sourceSampleAssetsModified\":false,\"narrativeDemoComplete\":false,\"created\":[],\"launch\":"+launch+"}");
        return 0;
    }
}
'@)
    $compiler=Join-Path $env:WINDIR 'Microsoft.NET/Framework64/v4.0.30319/csc.exe'
    $cmdEditor=Join-Path $engine 'Engine/Binaries/Win64/UnrealEditor-Cmd.exe'
    & $compiler /nologo /target:exe ('/out:'+$cmdEditor) $source
    if ($LASTEXITCODE -ne 0) { throw 'Fixture compile failed.' }
    Copy-Item -LiteralPath $cmdEditor -Destination (Join-Path $engine 'Engine/Binaries/Win64/UnrealEditor.exe')
    $env:WJ_REVIEW_FIXTURE_CAPTURE=Join-Path $temporary 'captured-phases.txt'
    $env:WJ_REVIEW_FIXTURE_FAIL_PHASE='none'
    $env:WJ_REVIEW_FIXTURE_MODE='boundKellan'
    Invoke-Review -PrepareOnly
    Assert ($code -eq 0) 'Prepare and fresh-process reload failed in Windows PowerShell 5.1.'
    $phases=Get-Content -LiteralPath $env:WJ_REVIEW_FIXTURE_CAPTURE
    Assert ($phases.Count -eq 2 -and $phases[0].StartsWith('prepare:') -and $phases[1].StartsWith('verify:') -and $phases[0].Split(':')[1] -ne $phases[1].Split(':')[1]) 'Preparation/reload must use distinct processes.'
    Assert ((Get-Content -LiteralPath $project -Raw) -ceq $original) 'Original descriptor modified.'
    Assert ((Get-FileHash -LiteralPath $config).Hash -eq $configHash) 'Original config modified.'
    Assert (@(Get-ChildItem -LiteralPath $sample -Filter 'WJInspect_*.uproject').Count -eq 0) 'Temporary descriptor not cleaned.'
    $wrapper=Join-Path $output 'Run-MovementReview.cmd'
    Assert (Test-Path -LiteralPath $wrapper) 'One-command repeat launch missing.'
    Assert (-not (Test-Path -LiteralPath (Join-Path $output 'session.json'))) 'PrepareOnly started a game.'
    Invoke-Review -RunOnly
    Assert ($code -eq 0) 'RunOnly failed.'
    $session=Get-Content -LiteralPath (Join-Path $output 'session.json') -Raw | ConvertFrom-Json
    $game=Get-Process -Id $session.pid
    Assert (-not $game.HasExited) 'Launcher waited for the persistent rendered child or killed it.'
    $capture=$env:WJ_REVIEW_FIXTURE_CAPTURE+'.game'
    for ($attempt=0; $attempt -lt 10 -and -not (Test-Path -LiteralPath $capture); $attempt++) { Start-Sleep -Milliseconds 100 }
    $arguments=Get-Content -LiteralPath $capture
    Assert ($arguments[0] -eq $project) 'Spaced/Unicode project path was not preserved.'
    Assert ($arguments -contains '-game' -and $arguments -notcontains '-NullRHI') 'Rendered launch must use a real RHI.'
    Assert ($session.graphicsVerified -eq $false) 'Launch request was incorrectly certified as graphics verification.'
    $game.Kill(); [void]$game.WaitForExit(5000); $game=$null
    $env:WJ_REVIEW_FIXTURE_MODE='sampleEditor'
    Invoke-Review -PrepareOnly
    Assert ($code -eq 0 -and ($lastOutput -join '\n').Contains('Automatic Kellan binding is not configured')) 'Original sample review was mislabeled as automatic binding or failed preparation.'
    Invoke-Review -RunOnly
    Assert ($code -eq 0) 'Original sample Editor repeat launch failed.'
    $session=Get-Content -LiteralPath (Join-Path $output 'session.json') -Raw | ConvertFrom-Json
    $game=Get-Process -Id $session.pid
    $arguments=Get-Content -LiteralPath ($env:WJ_REVIEW_FIXTURE_CAPTURE+'.game')
    Assert ($session.launchMode -eq 'sampleEditor' -and -not $game.HasExited) 'Source Editor launch mode/process was not preserved.'
    Assert ($arguments -notcontains '-game' -and $arguments -notcontains '-NullRHI' -and @($arguments | Where-Object { $_ -like '*?game=*' }).Count -eq 0) 'PIE character-picker path must open the Editor with its original game mode.'
    $game.Kill(); [void]$game.WaitForExit(5000); $game=$null
    $env:WJ_REVIEW_FIXTURE_MODE='boundKellan'
    $wrapperOutput=@(& $env:ComSpec /d /c $wrapper 2>&1); $wrapperCode=$LASTEXITCODE
    $wrapperOutput | ForEach-Object { Write-Host $_ }
    Assert ($wrapperCode -eq 0) 'One-command repeat wrapper failed with Unicode/spaced paths.'
    $session=Get-Content -LiteralPath (Join-Path $output 'session.json') -Raw | ConvertFrom-Json
    $game=Get-Process -Id $session.pid
    Assert (-not $game.HasExited) 'Repeat wrapper waited for or killed the game.'
    $game.Kill(); [void]$game.WaitForExit(5000); $game=$null
    $env:WJ_REVIEW_FIXTURE_FAIL_PHASE='verify'
    Invoke-Review -PrepareOnly
    Assert ($code -eq 1 -and ($lastOutput -join '\n').Contains('Intentional fixture failure')) 'Failed reload was not blocked or hid its reason.'
    Assert (@(Get-ChildItem -LiteralPath $sample -Filter 'WJInspect_*.uproject').Count -eq 0) 'Failed reload left a descriptor.'
    $env:WJ_REVIEW_FIXTURE_FAIL_PHASE='none'
    [IO.File]::AppendAllText($wrapper,"rem edited by user`r`n")
    $editedHash=(Get-FileHash -LiteralPath $wrapper).Hash
    Invoke-Review -PrepareOnly
    Assert ($code -eq 1) 'User-edited wrapper was accepted for overwrite.'
    Assert ((Get-FileHash -LiteralPath $wrapper).Hash -eq $editedHash) 'User-edited wrapper was overwritten.'
    [IO.File]::WriteAllText($project,$original.Replace('5.8','5.7'))
    Invoke-Review -PrepareOnly
    Assert ($code -eq 1 -and (Get-Content -LiteralPath $project -Raw).Contains('5.7')) 'Wrong engine sample was upgraded or accepted.'
    [IO.File]::WriteAllText($project,$original)
    $helper=Join-Path (Join-Path $cacheRoot $revision) 'movement_review.py'
    [IO.File]::AppendAllText($helper,"`n# local user edit`n")
    $helperHash=(Get-FileHash -LiteralPath $helper).Hash
    Invoke-Review -PrepareOnly
    Assert ($code -eq 1 -and (Get-FileHash -LiteralPath $helper).Hash -eq $helperHash) 'Changed helper was executed or overwritten.'
    Write-Host "Movement review Windows PowerShell 5.1/native handle fixtures: $checks checks passed. No Unreal/GPU test."
} finally {
    if ($game -and -not $game.HasExited) { $game.Kill(); [void]$game.WaitForExit(5000) }
    $env:WJ_REVIEW_FIXTURE_FAIL_PHASE=$previousPhase; $env:WJ_REVIEW_FIXTURE_CAPTURE=$previousCapture
    $env:WJ_REVIEW_FIXTURE_MODE=$previousMode
    if (Test-Path -LiteralPath $temporary) { Remove-Item -LiteralPath $temporary -Recurse -Force }
}
exit 0
